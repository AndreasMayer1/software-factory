/// Design Token Pre-Processing Script (W3C DTCG Format)
///
/// Why: This script processes tokens.json and generates type-safe Dart classes.
/// We use manual generation instead of design_tokens_builder because:
/// 1. design_tokens_builder doesn't support runtime theme switching
/// 2. We need factor-based spacing (base × factor) which requires computation
/// 3. We have two orthogonal theme dimensions (brightness × animation mode)
/// 4. Full control over W3C DTCG format parsing and generated output
///
/// Source: requirements_tasks/.../2026-01-16_01_plan_implementation.md
///
/// Usage: dart run scripts/process_design_tokens.dart
library;

import 'dart:convert';
import 'dart:io';

void main() async {
  print('Processing design tokens (W3C DTCG format)...\n');

  try {
    // Read tokens.json
    final tokensFile = File('lib/config/theme/tokens.json');
    if (!tokensFile.existsSync()) {
      throw Exception('tokens.json not found');
    }

    final tokensJson =
        jsonDecode(await tokensFile.readAsString()) as Map<String, dynamic>;
    print('Read tokens.json');

    // Extract sections
    final primitives = tokensJson['primitives'] as Map<String, dynamic>;
    final semantic = tokensJson['semantic'] as Map<String, dynamic>?;
    final theme = tokensJson['theme'] as Map<String, dynamic>?;
    final component = tokensJson['component'] as Map<String, dynamic>?;

    // Generate tokens.g.dart
    final tokensOutput = _generateTokensFile(primitives, semantic, component);
    await File('lib/config/theme/tokens.g.dart').writeAsString(tokensOutput);
    print('Generated: lib/config/theme/tokens.g.dart');

    // Generate animation_tokens.g.dart
    if (theme != null) {
      final animationOutput = _generateAnimationTokensFile(primitives, theme);
      await File('lib/config/theme/animation_tokens.g.dart')
          .writeAsString(animationOutput);
      print('Generated: lib/config/theme/animation_tokens.g.dart');
    }

    print('\nToken generation complete!');
    print('Run "flutter test -d windows" to verify.');
  } catch (e, stackTrace) {
    print('\nError: $e');
    print('Stack trace: $stackTrace');
    exit(1);
  }
}

/// Generate main tokens.g.dart file
String _generateTokensFile(
  Map<String, dynamic> primitives,
  Map<String, dynamic>? semantic,
  Map<String, dynamic>? component,
) {
  final buffer = StringBuffer();

  // Header
  buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
  buffer.writeln('// Generated by: dart run scripts/process_design_tokens.dart');
  buffer.writeln('// Source: lib/config/theme/tokens.json (W3C DTCG format)');
  buffer.writeln('//');
  buffer.writeln('// Why: Manual generation provides full control over:');
  buffer.writeln('// - Factor-based spacing computation (base × factor)');
  buffer.writeln('// - W3C DTCG format parsing');
  buffer.writeln('// - Runtime theme switching support');
  buffer.writeln('// - Generated API design');
  buffer.writeln();
  buffer.writeln('// ignore_for_file: public_member_api_docs');
  buffer.writeln();
  buffer.writeln("import 'package:flutter/material.dart';");
  buffer.writeln();

  // Generate SpacingTokens with factor-based computation
  buffer.writeln(_generateSpacingTokens(primitives['spacing']));
  buffer.writeln();

  // Generate BorderRadiusTokens
  buffer.writeln(_generateBorderRadiusTokens(primitives['borderRadius']));
  buffer.writeln();

  // Generate FontSizeTokens
  buffer.writeln(_generateFontSizeTokens(primitives['fontSize']));
  buffer.writeln();

  // Generate ColorTokens
  buffer.writeln(_generateColorTokens(primitives['color']));
  buffer.writeln();

  // Generate SemanticColorTokens
  if (semantic != null && semantic['color'] != null) {
    buffer.writeln(_generateSemanticColorTokens(semantic['color'], primitives));
    buffer.writeln();
  }

  // Generate ComponentTokens
  if (component != null) {
    buffer.writeln(_generateComponentTokens(component, primitives));
    buffer.writeln();
  }

  // Generate BuildContext extension
  buffer.writeln(_generateContextExtension(semantic != null, component != null));

  return buffer.toString();
}

/// Generate factor-based spacing tokens
String _generateSpacingTokens(Map<String, dynamic>? spacing) {
  if (spacing == null) return '// No spacing tokens defined';

  final base = _parseValue(spacing['base']?['\$value']);
  final scale = spacing['scale'] as Map<String, dynamic>?;

  final buffer = StringBuffer();
  buffer.writeln('/// Factor-based spacing tokens.');
  buffer.writeln('/// Base unit: ${base.toStringAsFixed(0)}px');
  buffer.writeln('/// All values computed as: base × factor');
  buffer.writeln('class SpacingTokens {');
  buffer.writeln('  const SpacingTokens();');
  buffer.writeln();
  buffer.writeln('  /// Base spacing unit');
  buffer.writeln('  static const double base = $base;');
  buffer.writeln();

  if (scale != null) {
    scale.forEach((name, config) {
      if (name.startsWith('\$')) return;
      if (config is Map && config.containsKey('\$value')) {
        final factor = (config['\$value'] as num).toDouble();
        final computed = base * factor;
        final desc = config['\$description'] as String?;
        final safeName = _sanitizeName(name);

        if (desc != null) {
          buffer.writeln('  /// $desc');
        } else {
          buffer.writeln(
              '  /// ${computed.toStringAsFixed(0)}px (base × $factor)');
        }
        buffer.writeln('  static const double $safeName = $computed;');
        buffer.writeln();
      }
    });
  }

  buffer.writeln('}');
  return buffer.toString();
}

